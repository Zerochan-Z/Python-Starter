# Parentheses ()
my_tuple = (1, 2, 3)   # Immutable list
print("hi")            # Function call

# Square Brackets []
my_list = [1, 2, 3]    # Mutable vector
my_list[0]             # Indexing

# Curly Braces {}
my_dict = {"key": "value"}  # Map/Key-Value store
my_set = {1, 2, 3}          # Unique values (if no colons)