# Part 1: List
fruits = ["apple", "banana", "orange"]

print(fruits[0])
print(fruits[-1])
fruits.append("grape")
print(fruits)

# Part 2: Tuple
coordinates = (10, 20)

print(coordinates)
print(coordinates[0])

# Part 3: Dictionary
person = {
    "name": "Avo",
    "age": 19,
    "city": "Beijing"
}

print(person)
print(person["city"])

# Part 4: Set
unique_numbers = {1, 2, 3, 2, 4, 1}
print(unique_numbers)